#2. Дана строка, состоящая из русских слов, разделенных пробелами (одним или несколькими).
# Вывести строку, содержащую эти же слова, разделенные одним пробелом и расположенные в обратном порядке.

# Присваеваем переменной s строковый водимый параметр от пользовталея
s = str(input("Введите русские символы через пробел: "))
# вводим новую переменную это таже переменная s но прогнананая через метод .split()
# который разбивает строку по любым пробельным символам и автоматически убирает лишние пробелы по краям
words = s.split()
# дальше так как лишние пробелы убраны то words переменная станет списком: пример есл ввести слов абрикос то ['слово', 'абрикос']
# и тогда создаем финальную переменную result и используем метод .join, разделитель.join(список_строк)
# строка у нас words и разделитель у нас пробел ' '
# добавляем переменной строки срез [::-1] чтобы символы ли в обратном порядке sequence[start:stop:step] где старт и стоп у нас отстувует, а шаг -1
result = ' '.join(words[::-1])
# и выводим результат финальную переменную result
print(result)




