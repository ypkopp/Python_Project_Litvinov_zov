# Сначала вводим переменную строковую запрошиваем, даллее используем метод для строк .swapcase - меняет регистр всех буквенных символов в строке на противоположный
# .swapcase - меняет регистр всех буквенных символов в строке на противоположный
s = str(input("Введите символы: ").swapcase())
# и далее выводим запрашиваемые символы со сменной ПРОПИСНЫХ на строковые и наоборот.
print(s)
