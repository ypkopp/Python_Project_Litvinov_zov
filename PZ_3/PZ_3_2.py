#2. Даны три числа. Найти среднее из них (то есть число, расположенное между наименьшим и наибольшим).
#  водим цикл для удобства
while True:
    #  водим цикл пока не будет тру
    while True:
            #водим конструкцию для обработки сключений try
            try:
                #запрос 3х чисел
                num1 = int(input('Введите 1 число: '))
                num2 = int(input('Введите 2 число: '))
                num3 = int(input('Введите 3 число: '))
                #вводим условие  по которому оперделяем какое из трех чисел среднее
                # Проверяем является ли num1 средним
                if (num2 <= num1 <= num3) or (num3 <= num1 <= num2):
                    middle_num = num1
                # Проверяем является ли num2  средним
                elif (num1 <= num2 <= num3) or (num3 <= num2 <= num1):
                    middle_num = num2
                # Если не первое и не второе то средним остается только num3
                else:
                    middle_num = num3
                #выводим из цикла

                break
            #В ином случае ошибка
            except ValueError:
                print('Ошибка: ввели не целое число или вели текст или буквы или пустую строку')

    #выводим нужное число
    print(middle_num)